import { fieldLabel } from "../theme";

export function gradePrompt(q, answer) {
  return `あなたは情報処理安全確保支援士試験（SC）科目B（記述式）の採点官です。受験者の答案を採点してください。

${q.scenario ? "【状況設定】" + q.scenario + "\n" : ""}${q.exhibit ? "【図表】\n" + q.exhibit + "\n" : ""}【設問】${q.question}
${q.charLimit ? "【字数制限】" + q.charLimit + "字以内\n" : ""}【模範解答】${q.modelAnswer}
【重要キーワード・概念】${(q.keywords || []).join("、")}
【受験者の答案】${answer}

採点基準:
- 設問の問い方に対応した答え方か（理由を問われたら「〜から/ため」で結ぶ、名称を問われたら名称を明示、など「記述の型」）
- 重要キーワード・概念を押さえているか（表現が違っても技術的に同義なら減点しない）
- 因果関係と技術的正確性
- 字数制限がある場合、制限内か・要素を絞り込めているか

以下のJSONオブジェクトのみを出力してください。前置き、説明、コードブロック記法は一切禁止です。
{"score": 0から10の整数, "verdict": "合格レベル" | "あと一歩" | "要復習", "good": "答案の良い点（1文、簡潔に）", "improve": "改善点。添削者として具体的に、どう書けば得点になるかを示す（2文以内）", "missing": ["不足しているキーワードや概念"]}`;
}

export function genPrompt(fieldId, type) {
  const fl = fieldLabel(fieldId);
  const serverHint = fieldId === "server"
    ? "受験者はサーバ運用の実務経験が少ないため、ログ分析・OS要塞化・アカウント管理・パッチ運用・バックアップなど運用現場の定番論点を優先すること。"
    : "";
  if (type === "recall") {
    return `情報処理安全確保支援士試験（SC）の学習用に、「${fl}」分野の書き出し訓練問題を1問作成してください。頻出の技術要素について、仕組み・目的・対策を自分の言葉で書き出させる形式です。${serverHint}

以下のJSONオブジェクトのみを出力（前置き・コードブロック禁止）:
{"type": "recall", "field": "${fieldId}", "question": "〜を書き出せ。という形式の問題文", "modelAnswer": "模範解答（2〜4文、技術的に正確に）", "keywords": ["重要キーワード3〜4個"]}`;
  }
  return `情報処理安全確保支援士試験（SC）科目B（午後・記述式）の形式で、「${fl}」分野のオリジナル演習問題を1問作成してください。実務的なインシデントや設計判断のシナリオを設定し、字数制限つきの記述設問を1つ付けます。SC午後の出題傾向（本文の状況から根拠を特定し、簡潔に記述させる）に沿ってください。${serverHint}

以下のJSONオブジェクトのみを出力（前置き・コードブロック禁止）:
{"type": "kijutsu", "field": "${fieldId}", "scenario": "状況設定（150〜250字。企業名はアルファベット1文字＋社）", "question": "設問（〜をXX字以内で述べよ。の形式）", "charLimit": 30から60の整数, "modelAnswer": "字数制限内の模範解答", "keywords": ["採点上の重要キーワード3個"]}`;
}
